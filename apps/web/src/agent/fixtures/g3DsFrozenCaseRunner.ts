function weldAutoGeneratedFaceVertices(doc: GeometryDocument): GeometryDocument {
  const remap = new Map<string, string>()
  const keptPoint3s: Array<{ id: string; label?: string; position: { x: number; y: number; z: number } }> = []
  for (const p of doc.primitives) {
    if (p.type !== "point3") continue
    const isAutoTopologyVertex = /^(?:face|solid)-\d+:v\d+$/.test(p.id)
    if (isAutoTopologyVertex) {
      const canonical = keptPoint3s.find(
        (existing) =>
          (p.label === undefined || p.label === existing.label) &&
          Math.hypot(
            p.position.x - existing.position.x,
            p.position.y - existing.position.y,
            p.position.z - existing.position.z
          ) <= 1e-9
      )
      if (canonical) {
        remap.set(p.id, canonical.id)
        continue
      }
    }
    keptPoint3s.push({ id: p.id, ...(p.label === undefined ? {} : { label: p.label }), position: p.position })
  }
  if (remap.size === 0) return doc
  return {
    ...doc,
    primitives: doc.primitives
      .filter((p) => !remap.has(p.id))
      .map((p) => {
        if (p.type === "edge3") {
          return {
            ...p,
            pointIds: [remap.get(p.pointIds[0]) ?? p.pointIds[0], remap.get(p.pointIds[1]) ?? p.pointIds[1]] as [string, string]
          }
        }
        if (p.type === "face3" && Array.isArray(p.pointIds)) {
          return { ...p, pointIds: p.pointIds.map((id) => remap.get(id) ?? id) }
        }
        if (p.type === "polyhedron3" && Array.isArray(p.vertexIds)) {
          return { ...p, vertexIds: p.vertexIds.map((id) => remap.get(id) ?? id) }
        }
        return p
      })
  }
}

function materializeSliceDocument(
  slice: CandidateSliceArtifact,
  workspace: "geometry3d" | "conics",
  index: number
): GeometryDocument | null {
  if (slice.document) return slice.document
  if (slice.plan && slice.plan.kind === "plan") {
    const compiled = compilePlan(slice.plan, {
      document: createEmptyDocument(workspace),
      conversationId: `frozen-slice-${index}`,
      documentGeneration: 0,
      workspace
    })
    return compiled.ok && compiled.draftDocument ? createDefaultCadLayout(weldAutoGeneratedFaceVertices(compiled.draftDocument)) : null
  }
  return null
}


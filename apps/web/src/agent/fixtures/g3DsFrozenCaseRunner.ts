export interface Task6FunnelReport {
  readonly denominator: number
  readonly modelInvokedCount: number
  readonly firstAttemptPassedCount: number
  readonly contractPassedCount: number
  readonly certificatePassedCount: number
  readonly liveRenderedCount: number
  readonly committedCount: number
  readonly totalRequests: number
  readonly totalUsageEvents: number
  readonly totalInputBytes: number
  readonly totalInputTokens: number
  readonly totalOutputTokens: number
  readonly costKnown: false
  readonly costUsd: null
  readonly shouldStopBatch: boolean
  readonly stopReason?: "mixed_read_plan_recurrence" | "consecutive_failures"
}

export function aggregateTask6FunnelReport(
  entries: readonly Task6CaseFunnelEntry[],
  options: { readonly failureStopThreshold: number }
): Task6FunnelReport {
  let modelInvokedCount = 0
  let firstAttemptPassedCount = 0
  let contractPassedCount = 0
  let certificatePassedCount = 0
  let liveRenderedCount = 0
  let committedCount = 0
  let totalRequests = 0
  let totalUsageEvents = 0
  let totalInputBytes = 0
  let totalInputTokens = 0
  let totalOutputTokens = 0
  let consecutiveFailures = 0
  let stopReason: Task6FunnelReport["stopReason"]

  for (const e of entries) {
    if (e.modelInvoked) modelInvokedCount += 1
    if (e.firstAttemptPassed) firstAttemptPassedCount += 1
    if (e.contractStatus === "passed") contractPassedCount += 1
    if (e.certificateStatus === "passed") certificatePassedCount += 1
    if (e.renderStatus === "dsLiveRendered") liveRenderedCount += 1
    if (e.commitStatus === "passed") committedCount += 1
    totalRequests += e.requestsUsed
    totalUsageEvents += e.usageEventsReported
    totalInputBytes += e.inputBytes
    totalInputTokens += e.inputTokens
    totalOutputTokens += e.outputTokens

    if (e.firstBoundary === "tool_protocol" && e.firstCode === "mixed_read_plan") {
      stopReason = stopReason ?? "mixed_read_plan_recurrence"
    }
    if (e.contractStatus === "passed" && e.certificateStatus === "passed") {
      consecutiveFailures = 0
    } else {
      consecutiveFailures += 1
      if (consecutiveFailures >= options.failureStopThreshold) {
        stopReason = stopReason ?? "consecutive_failures"
      }
    }
  }

  return {
    denominator: entries.length,
    modelInvokedCount,
    firstAttemptPassedCount,
    contractPassedCount,
    certificatePassedCount,
    liveRenderedCount,
    committedCount,
    totalRequests,
    totalUsageEvents,
    totalInputBytes,
    totalInputTokens,
    totalOutputTokens,
    // Even if all usage events report tokens, provider billing is never inferred inside app code.
    costKnown: false,
    costUsd: null,
    shouldStopBatch: stopReason !== undefined,
    ...(stopReason === undefined ? {} : { stopReason })
  }
}

export function evaluateFrozenCandidateSet(
  publicCase: PublicFrozenCaseInput,
  slices: readonly CandidateSliceArtifact[],
  contract?: DrawingContractCase,
  onVerifiedCandidate?: (candidate: VerifiedFrozenCandidate) => void
): {
  readonly candidateSet: readonly CandidateSliceCertificate[]
  readonly contractStatus: FrozenDsCaseResult["contractStatus"]
} {
  const candidateSet: CandidateSliceCertificate[] = []
  const evalSlices: PolicyCandidateSlice[] = []
  const validatedDocuments: VerifiedFrozenCandidate[] = []
  let allCertificatesPassed = slices.length > 0
  let anyCertificateHashMismatch = false
  let anyLineageHashCollision = false
  const seenLineageByHash = new Map<string, string>()

  for (let i = 0; i < slices.length; i += 1) {
    const slice = slices[i]!
    const lineageKey = `${slice.scopeId}::${slice.stateId ?? "shared"}::${slice.branchId ?? "default"}`
    const doc = materializeSliceDocument(slice, publicCase.workspace, i)
    if (!doc) {
      allCertificatesPassed = false
      candidateSet.push({
        scopeId: slice.scopeId,
        ...(slice.stateId === undefined ? {} : { stateId: slice.stateId }),
        ...(slice.branchId === undefined ? {} : { branchId: slice.branchId }),
        ...(slice.parentCandidateHash === undefined ? {} : { parentCandidateHash: slice.parentCandidateHash }),
        lineageKey,
        documentHash: "",
        candidateHash: "",
        certificateStatus: "blocked"
      })
      continue
    }

    const actualCandidateHash = canonicalContentHash(doc)
    const boundHash = slice.overrideCertificateHash ?? actualCandidateHash
    const cert = certifyDrawingAgainstContract({
      prompt: publicCase.prompt,
      document: doc,
      candidateHash: boundHash,
      sourceHash: boundHash,
      ...(slice.plan === undefined ? {} : { plan: slice.plan }),
      selectedScopeId: toCertificateScopeId(slice.scopeId)
    })
    const hashMatches = boundHash === actualCandidateHash
    if (!hashMatches) anyCertificateHashMismatch = true

    const statePolicy = contract?.displayPolicy.multiStateHandling ?? ""
    const enumeratedStates = statePolicy.startsWith("enumerate:")
      ? statePolicy.slice("enumerate:".length).split(",").map((s) => s.trim()).filter(Boolean)
      : []
    const sliceStateIdx = slice.stateId ? enumeratedStates.indexOf(slice.stateId) : -1
    let certStatusAfterPreFoldGuard = cert.certificateStatus
    if (
      contract &&
      certStatusAfterPreFoldGuard !== "passed" &&
      slice.stateId &&
      sliceStateIdx >= 0 &&
      sliceStateIdx < enumeratedStates.length - 1
    ) {
      const laterApexLabels = new Set<string>()
      for (const later of slices) {
        const laterIdx = later.stateId ? enumeratedStates.indexOf(later.stateId) : -1
        if (laterIdx > sliceStateIdx && later.plan?.kind === "plan") {
          for (const act of later.plan.actions) {
            if (act.actionId === "solid.fold" && typeof act.inputs?.apexAs === "string") {
              laterApexLabels.add(act.inputs.apexAs)
            }
          }
        }
      }
      const preContractCheck = evaluateDrawingContract(contract, doc, {
        verificationStatus: "passed",
        scopeId: slice.scopeId,
        stateId: slice.stateId
      })
      const postFoldPointOnlyFailures =
        (cert.failedObligations?.length ?? 0) > 0 &&
        cert.failedObligations!.every((f) => {
          const m = /点名缺失：([A-Z][^—\s]*)/.exec(f.detail)
          if (!m) return false
          const missingNames = m[1]!.split("、").map((n) => n.trim()).filter(Boolean)
          return missingNames.length > 0 && missingNames.every((n) => laterApexLabels.has(n))
        })
      if (certStatusAfterPreFoldGuard === "partial" && preContractCheck.passed && postFoldPointOnlyFailures) {
        certStatusAfterPreFoldGuard = "passed"
      }
    }

    let collidesWithDistinctStateOrBranch = false
    if (slice.stateId !== undefined || slice.branchId !== undefined) {
      const priorLineage = seenLineageByHash.get(actualCandidateHash)
      if (priorLineage && priorLineage !== lineageKey) {
        collidesWithDistinctStateOrBranch = true
        anyLineageHashCollision = true
      } else {
        seenLineageByHash.set(actualCandidateHash, lineageKey)
      }
    }

    const effectiveCertStatus: DrawingCertificateResult["certificateStatus"] =
      !hashMatches || collidesWithDistinctStateOrBranch ? "blocked" : certStatusAfterPreFoldGuard

    if (effectiveCertStatus !== "passed") {
      allCertificatesPassed = false
    }

    const failedObligations = [
      ...(certStatusAfterPreFoldGuard === "passed" ? [] : (cert.failedObligations?.map((f) => `${f.id}:${f.detail}`) ?? [])),
      ...(collidesWithDistinctStateOrBranch ? ["duplicate_lineage_hash"] : [])
    ]

    candidateSet.push({
      scopeId: slice.scopeId,
      ...(slice.stateId === undefined ? {} : { stateId: slice.stateId }),
      ...(slice.branchId === undefined ? {} : { branchId: slice.branchId }),
      ...(slice.parentCandidateHash === undefined ? {} : { parentCandidateHash: slice.parentCandidateHash }),
      lineageKey,
      documentHash: actualCandidateHash,
      candidateHash: actualCandidateHash,
      certificateStatus: effectiveCertStatus,
      ...(failedObligations.length > 0 ? { failedObligations } : {})
    })

    if (effectiveCertStatus === "passed") validatedDocuments.push({
      scopeId: slice.scopeId, candidateHash: actualCandidateHash, document: doc
    })
    const planAssumptions = slice.plan && slice.plan.kind === "plan" ? (slice.plan.assumptions ?? []).join("\n") : ""
    const combinedDiagnosisText = `${slice.answerText ?? ""}\n${planAssumptions}`
    const infeasibleDiagnosedSubquestions = (contract?.subquestions ?? [])
      .filter((sq) => sq.feasible === false && /无实数解|无实数点解|不存在|不成立|矛盾|不可行|infeasible/i.test(combinedDiagnosisText))
      .map((sq) => sq.id)
    evalSlices.push({
      scopeId: slice.scopeId,
      ...(slice.stateId === undefined ? {} : { stateId: slice.stateId }),
      ...(slice.branchId === undefined ? {} : { branchId: slice.branchId }),
      candidate: doc,
      options: {
        verificationStatus: effectiveCertStatus === "passed" ? "passed" : "failed",
        answerText: slice.answerText ?? null,
        ...(slice.scopeId === "shared" ? {} : { scopeId: slice.scopeId }),
        ...(slice.stateId === undefined ? {} : { stateId: slice.stateId }),
        ...(slice.branchId === undefined ? {} : { branchId: slice.branchId }),
        ...(infeasibleDiagnosedSubquestions.length > 0 ? { infeasibleDiagnosedSubquestions } : {})
      }
    })
  }

  let contractStatus: FrozenDsCaseResult["contractStatus"] = "failed"
  if (contract) {
    const policyEval = evaluateDrawingContractSetByPolicy(contract, evalSlices)
    contractStatus = policyEval.status
    if (anyCertificateHashMismatch || anyLineageHashCollision || (!allCertificatesPassed && contractStatus === "passed")) {
      contractStatus = "failed"
    }
  } else if (allCertificatesPassed) {
    contractStatus = "passed"
  }

  if (contract !== undefined && contractStatus === "passed" && validatedDocuments.length === candidateSet.length) {
    for (const candidate of validatedDocuments) onVerifiedCandidate?.(candidate)
  }
  return { candidateSet, contractStatus }
}

export async function runFrozenDsCase(
  rawPublicInput: {
    readonly id: string
    readonly prompt: string
    readonly confirmedFigureRefs?: readonly unknown[]
    readonly workspace: "geometry3d" | "conics"
  },
  provider: FrozenDsProvider,
  budget: Budget | ExamRunBudget,
  options: {
    readonly contract?: DrawingContractCase
    readonly onVerifiedCandidate?: (candidate: VerifiedFrozenCandidate) => void
  } = {}
): Promise<FrozenDsCaseResult> {
  // Always strip any extra non-public fields before calling the model provider or planner.
  const publicCase = projectPublicFrozenCaseInput(rawPublicInput)

  const controller = new AbortController()
  const response: FrozenDsCaseRunnerResponse =
    typeof provider === "function"
      ? await provider(publicCase, budget)
      : await (async () => {
          const outcome = await provider.plan(buildPlanRequestForPublicInput(publicCase, budget, controller.signal))
          if ("plan" in outcome && outcome.plan.kind === "plan") {
            const rootPlan = outcome.plan
            const slices: CandidateSliceArtifact[] =
              outcome.candidateSlices && outcome.candidateSlices.length > 0
                ? outcome.candidateSlices.map((s) => ({
                    scopeId: s.scopeId,
                    ...(s.stateId === undefined ? {} : { stateId: s.stateId }),
                    ...(s.branchId === undefined ? {} : { branchId: s.branchId }),
                    plan: s.plan,
                    ...(s.answerText === undefined && rootPlan.answer === undefined
                      ? {}
                      : { answerText: s.answerText ?? rootPlan.answer })
                  }))
                : [{ scopeId: "shared", plan: rootPlan, answerText: rootPlan.answer }]
            return {
              modelInvoked: true,
              slices
            }
          }
          return { modelInvoked: true, slices: [] }
        })()

  const { candidateSet, contractStatus } = evaluateFrozenCandidateSet(publicCase, response.slices, options.contract, options.onVerifiedCandidate)

  return {
    candidateSet,
    modelInvoked: response.modelInvoked,
    contractStatus,
    renderStatus: "pending",
    commitStatus: "pending"
  }
}

export function compareLegacySingleVsMultiSliceReplay(
  contract: DrawingContractCase,
  singleCandidate: unknown,
  multiSlices: readonly PolicyCandidateSlice[]
): {
  readonly legacySingleStatus: "passed" | "partial" | "failed" | "incomplete"
  readonly multiSliceStatus: "passed" | "partial" | "failed" | "incomplete"
  readonly diverged: boolean
} {
  const singleRes = evaluateDrawingContract(contract, singleCandidate, { verificationStatus: "passed" })
  const multiRes = evaluateDrawingContractSetByPolicy(contract, multiSlices)
  return {
    legacySingleStatus: singleRes.status,
    multiSliceStatus: multiRes.status,
    diverged: singleRes.status !== multiRes.status
  }
}

/** Executes the actual ds_action planner and publishes only validated trace fields. */
export async function runFrozenDsCaseTraced(
  publicInput: Parameters<typeof runFrozenDsCase>[0],
  budget: Budget | ExamRunBudget,
  dependencies: ModelPlannerDependencies,
  options: {
    readonly contract?: DrawingContractCase
    readonly revision: string
    readonly runId: string
    readonly onTrace: (trace: G3CaseTrace) => void
    readonly onVerifiedCandidate?: (candidate: VerifiedFrozenCandidate) => void
  }
): Promise<FrozenDsCaseResult> {
  let trace = createG3CaseTrace({ caseId: publicInput.id, runId: options.runId, revision: options.revision })
  const planner = createModelPlanner({
    ...dependencies,
    onStructuredDiagnostic: (event) => {
      dependencies.onStructuredDiagnostic?.(event)
      if (event.kind === "request") {
        trace = recordRequestTrace(trace, {
          index: event.index, toolNames: event.toolNames,
          responseKind: event.responseKind, usageKnown: event.usageKnown
        })
      } else if (event.kind === "action") {
        trace = recordActionReceipt(trace, event)
        if (event.resultStatus !== "accepted") trace = recordBoundary(trace, { boundary: "schema", code: event.blockerCode ?? "action_blocked" })
      } else {
        trace = recordBoundary(trace, event)
      }
    }
  })
  try {
    // This runner sends only a text userMessage. Figure references are not image bytes:
    // do not spend a provider request or claim a complete exam drawing from missing input.
    if (options.contract?.inputMode === "text_with_figure_reference") {
      trace = recordBoundary(trace, { boundary: "contract", code: "input_figure_missing" })
      return { candidateSet: [], modelInvoked: false, contractStatus: "incomplete", renderStatus: "pending", commitStatus: "pending" }
    }
    return await runFrozenDsCase(publicInput, planner, budget, {
      ...(options.contract === undefined ? {} : { contract: options.contract }),
      ...(options.onVerifiedCandidate === undefined ? {} : { onVerifiedCandidate: options.onVerifiedCandidate })
    })
  } finally {
    options.onTrace(markMissingActionReceipts(trace))
  }
}
